/// `bytes` through an upper-half `table` (ASCII below 0x80).
pub(crate) fn decode(bytes: &[u8], table: &[char; 128]) -> String {
    bytes
        .iter()
        .map(|&b| {
            if b < 0x80 {
                char::from(b)
            } else {
                table[usize::from(b - 0x80)]
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn czech_code_pages() {
        // „Příliš žluťoučký kůň“ in each of the three.
        assert_eq!(
            decode(
                b"P\xa9\xa1li\xa8 \x91lu\x9fou\x87k\x98 k\x96\xa4",
                &KAMENICKY
            ),
            "Příliš žluťoučký kůň"
        );
        assert_eq!(
            decode(b"P\xfd\xa1li\xe7 \xa7lu\x9cou\x9fk\xec k\x85\xe5", &CP852),
            "Příliš žluťoučký kůň"
        );
        assert_eq!(decode(b"\xb3\xc4\xda", &CP437), "│─┌");
        assert_eq!(decode(b"\xcb\xeb", &KOI8_CS), "ĺĹ");
    }
}
